CREATE TABLE IF NOT EXISTS result_import_batches (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  examination_id BIGINT UNSIGNED NOT NULL,
  assessment_id BIGINT UNSIGNED NOT NULL,
  class_group_id BIGINT UNSIGNED NOT NULL,
  subject_id BIGINT UNSIGNED NOT NULL,
  original_filename VARCHAR(255) NOT NULL,
  storage_key CHAR(64) NULL,
  uploaded_by BIGINT UNSIGNED NOT NULL,
  status ENUM('review','ready','applied','cancelled') NOT NULL DEFAULT 'review',
  total_rows INT UNSIGNED NOT NULL DEFAULT 0,
  matched_rows INT UNSIGNED NOT NULL DEFAULT 0,
  review_rows INT UNSIGNED NOT NULL DEFAULT 0,
  error_rows INT UNSIGNED NOT NULL DEFAULT 0,
  applied_rows INT UNSIGNED NOT NULL DEFAULT 0,
  notes VARCHAR(500) NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  applied_at DATETIME NULL,
  KEY idx_batch_scope (examination_id, class_group_id, subject_id, status),
  KEY idx_batch_uploader (uploaded_by, created_at),
  CONSTRAINT fk_batch_exam FOREIGN KEY (examination_id) REFERENCES examinations(id) ON DELETE RESTRICT,
  CONSTRAINT fk_batch_assessment FOREIGN KEY (assessment_id) REFERENCES assessments(id) ON DELETE RESTRICT,
  CONSTRAINT fk_batch_class FOREIGN KEY (class_group_id) REFERENCES class_groups(id) ON DELETE RESTRICT,
  CONSTRAINT fk_batch_subject FOREIGN KEY (subject_id) REFERENCES subjects(id) ON DELETE RESTRICT,
  CONSTRAINT fk_batch_uploader FOREIGN KEY (uploaded_by) REFERENCES users(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS result_import_rows (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  batch_id BIGINT UNSIGNED NOT NULL,
  row_number INT UNSIGNED NOT NULL,
  raw_name VARCHAR(180) NOT NULL,
  raw_admission VARCHAR(40) NULL,
  raw_mark VARCHAR(30) NULL,
  mark DECIMAL(7,2) NULL,
  match_status ENUM('matched','review','approved','rejected','applied','error') NOT NULL DEFAULT 'review',
  match_method ENUM('admission','exact_name','fuzzy','manual','none') NOT NULL DEFAULT 'none',
  matched_student_id BIGINT UNSIGNED NULL,
  suggested_student_id BIGINT UNSIGNED NULL,
  confidence DECIMAL(5,2) NULL,
  candidates_json JSON NULL,
  error_message VARCHAR(500) NULL,
  reviewed_by BIGINT UNSIGNED NULL,
  reviewed_at DATETIME NULL,
  result_id BIGINT UNSIGNED NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_batch_row (batch_id, row_number),
  KEY idx_row_status (batch_id, match_status),
  KEY idx_row_student (matched_student_id),
  KEY idx_row_result (result_id),
  CONSTRAINT fk_row_batch FOREIGN KEY (batch_id) REFERENCES result_import_batches(id) ON DELETE CASCADE,
  CONSTRAINT fk_row_student FOREIGN KEY (matched_student_id) REFERENCES students(id) ON DELETE SET NULL,
  CONSTRAINT fk_row_suggestion FOREIGN KEY (suggested_student_id) REFERENCES students(id) ON DELETE SET NULL,
  CONSTRAINT fk_row_result FOREIGN KEY (result_id) REFERENCES results(id) ON DELETE SET NULL,
  CONSTRAINT fk_row_reviewer FOREIGN KEY (reviewed_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
