<?php
declare(strict_types=1);
require_once dirname(__DIR__) . '/bootstrap.php';

use School\Core\SchoolAuth;
use School\Repositories\SchoolAnalyticsRepository;

SchoolAuth::requireLogin();
$user = SchoolAuth::user();
if (!$user) { header('Location: ' . SCHOOL_BASE_URL . 'login.php'); exit; }
$role = school_current_role($user);
if (!SchoolAuth::hasPermission('reports.export') && !SchoolAuth::hasPermission('analytics.school') && !SchoolAuth::hasPermission('analytics.academic') && !SchoolAuth::hasPermission('analytics.finance') && !SchoolAuth::hasPermission('analytics.assigned')) {
    http_response_code(403);
    exit('Export is not permitted for your account.');
}

$filters = [
    'year_id' => (int) ($_GET['year_id'] ?? 0),
    'term_id' => (int) ($_GET['term_id'] ?? 0),
    'class_id' => (int) ($_GET['class_id'] ?? 0),
    'from' => (string) ($_GET['from'] ?? ''),
    'to' => (string) ($_GET['to'] ?? ''),
];
$data = (new SchoolAnalyticsRepository())->data($user, $role, $filters);
$context = $data['context'];
$filename = 'school-insights-' . preg_replace('/[^0-9]/', '', (string) ($context['year']['name'] ?? 'all')) . '-' . date('Ymd-His') . '.csv';

header('Content-Type: text/csv; charset=UTF-8');
header('Content-Disposition: attachment; filename="' . $filename . '"');
header('Cache-Control: no-store');

$out = fopen('php://output', 'w');
fwrite($out, "\xEF\xBB\xBF"); // Excel-friendly UTF-8 BOM.

$row = static function (array $cells) use ($out): void { fputcsv($out, $cells); };
$section = static function (string $title) use ($row): void { $row([]); $row([$title]); };

$row(['School insights export']);
$row(['School', $context['school']['name'] ?? 'School Management']);
$row(['Academic year', $context['year']['name'] ?? 'All years']);
$row(['Term', $context['term']['name'] ?? 'All terms']);
$row(['Class', $context['class']['name'] ?? 'All classes']);
$row(['Date range', $context['from'] . ' to ' . $context['to']]);
$row(['Generated at (UTC)', $context['generated_at']]);
$row(['Generated by', $user['full_name'] . ' (' . school_role_label($role) . ')']);

$section('Key indicators');
$row(['Metric', 'Value']);
foreach ([
    'Active learners' => $data['kpis']['students'],
    'Classes' => $data['kpis']['classes'],
    'Active staff' => $data['kpis']['staff'],
    'Teachers assigned' => $data['kpis']['teachers'],
    'Attendance rate %' => $data['kpis']['attendance_rate'],
    'Average mark %' => $data['kpis']['average_mark'],
    'Pass rate %' => $data['kpis']['pass_rate'],
    'Result entries' => $data['kpis']['result_entries'],
    'Fees charged' => $data['finance']['charged'],
    'Fees collected' => $data['finance']['paid'],
    'Fees outstanding' => $data['finance']['outstanding'],
    'Fees overdue' => $data['finance']['overdue'],
    'Collection rate %' => $data['finance']['collection_rate'],
] as $label => $value) $row([$label, $value]);

$section('Monthly admissions');
$row(['Month', 'Admissions']);
foreach ($data['admission_trend'] as $item) $row([$item['label'], $item['value']]);

$section('Attendance status');
$row(['Status', 'Records']);
foreach ($data['attendance_status'] as $item) $row([$item['label'], $item['value']]);

$section('Attendance by class');
$row(['Class', 'Present', 'Absent', 'Late']);
foreach ($data['attendance_by_class']['labels'] as $index => $label) {
    $row([$label, $data['attendance_by_class']['present'][$index] ?? 0, $data['attendance_by_class']['absent'][$index] ?? 0, $data['attendance_by_class']['late'][$index] ?? 0]);
}

$section('Class distribution');
$row(['Class', 'Learners']);
foreach ($data['class_distribution'] as $item) $row([$item['label'], $item['value']]);

$section('Finance');
$row(['Metric', 'Value']);
$row(['Invoices', $data['finance']['invoice_count']]);
$row(['Fully paid invoices', $data['finance']['paid_invoices']]);
$row(['Charged', $data['finance']['charged']]);
$row(['Collected', $data['finance']['paid']]);
$row(['Outstanding', $data['finance']['outstanding']]);
$row(['Overdue', $data['finance']['overdue']]);
$row(['Collection rate %', $data['finance']['collection_rate']]);
$row([]);
$row(['Month', 'Collected', 'Outstanding (current)']);
foreach ($data['finance']['monthly']['labels'] as $index => $label) {
    $row([$label, $data['finance']['monthly']['collected'][$index] ?? 0, $data['finance']['monthly']['outstanding'][$index] ?? 0]);
}
$row([]);
$row(['Payment method', 'Payments', 'Amount']);
foreach ($data['finance']['methods'] as $method) $row([$method['label'], $method['value'], $method['amount']]);
$row([]);
$row(['Learner', 'Admission', 'Class', 'Balance']);
foreach ($data['finance']['top_debtors'] as $debtor) $row([$debtor['name'], $debtor['admission'], $debtor['class'], $debtor['balance']]);

$section('Academic performance');
$row(['Subject', 'Average %', 'Entries', 'Pass rate %']);
foreach ($data['academic']['subjects'] as $subject) $row([$subject['label'], $subject['value'], $subject['entries'], $subject['pass_rate']]);
$row([]);
$row(['Grade', 'Entries']);
foreach ($data['academic']['grades'] as $grade) $row([$grade['label'], $grade['value']]);
$row([]);
$row(['Term', 'Average %']);
foreach ($data['academic']['exam_trend'] as $item) $row([$item['label'], $item['value']]);
$row([]);
$row(['Learner', 'Admission', 'Class', 'Subjects', 'Average %']);
foreach ($data['academic']['top_students'] as $student) $row([$student['full_name'], $student['admission_number'], $student['class_name'], $student['subjects'], $student['average']]);

$section('Learners needing support');
$row(['Learner', 'Admission', 'Class', 'Attendance %', 'Fee balance']);
foreach ($data['at_risk'] as $risk) $row([$risk['full_name'], $risk['admission_number'], $risk['class_name'], $risk['attendance_rate'], $risk['balance']]);

fclose($out);
